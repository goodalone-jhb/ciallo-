/*-- 频率编码遥测（故障时替代"抽几下"）--------------------------------------
 * 传感器起不来时，不再抽动提示，而是把寄存器的真实内容编码成频率从 PA0 发出来，
 * 用万用表的频率档直接读数（0.049kHz 就是这么测出来的，说明频率档可靠）。
 *
 *     频率 = 800 + 25 × 数值  (Hz)
 *        0 -> 0.800kHz    3 -> 0.875kHz   15 -> 1.175kHz
 *       64 -> 2.400kHz  255 -> 7.175kHz
 *
 * 每个值响 3 秒、静音 1.5 秒。顺序固定六项，循环往复：
 *   A = 0x75 WHO_AM_I 的真实值（读失败 = 255 = 7.175kHz）
 *   B = 读 0x3B 卡在哪一步，这一项刻意拉开间距，不会读错：
 *         0.800kHz = 成功        1.600kHz = 地址字节无应答
 *         2.400kHz = 寄存器无应答  3.200kHz = 读地址无应答
 *   C = 0x3B 读到的值（读失败 = 255）
 *   D = 0x3F 加速度 Z 轴高字节（静止约 64 = 2.400kHz）
 *   E = 0x41 温度高字节（常温约 15 = 1.175kHz）
 *   F = 0x1A CONFIG（配置写过后应为 3）
 *
 * 注意：遥测会把 PA0 从定时器手里抢过来，两路舵机都不再输出，这是正常的。
 * 定型后改 0。 */
#ifndef EAR_TELEM_MODE
#define EAR_TELEM_MODE        0
#endif

/*-- SWD 在线快照（比频率编码高一档）----------------------------------------
 * 传感器起不来时，固件不再抽动、不再发音，而是把"现场记录"持续写在 RAM 的
 * 固定地址 0x20000500 上，PC 端用 DAPLink 直接读走即可 —— 不需要示波器、
 * 不需要万用表、不需要改一轮代码烧一次。
 *
 * 记录内容（0x20000500 起，共 288 字节，小端）：
 *   0x00 magic      'EARD'，读到它就说明这片 RAM 确实是本固件写的
 *   0x04 seq        刷新计数（每 400ms +1）：它不动 = CPU 没在跑
 *   0x08 tick       SysTick 毫秒数
 *   0x0C fault      启动阶段定下的故障码（就是原来"抽几下"的那个数字）
 *   0x10 ack68      0x68 地址是否有应答（1 = 有）
 *   0x11 who68      0x68 的 WHO_AM_I（读失败填 0xFF）
 *   0x12 ack69 / 0x13 who69    同一个意思，AD0 接 VCC 的那个地址
 *   0x14 st68[4]    0x68 上 0x75/0x3B/0x41/0x1A 四个寄存器的读取状态
 *   0x18 st69[4]    0x69 同上
 *   0x1C nerr       0x00~0x7F 里读失败的寄存器个数
 *   0x20 reg[128]   0x00~0x7F 全寄存器镜像
 *   0xA0 status[128] 每个寄存器的读取状态：0=成功 1=地址无应答
 *                   2=寄存器无应答 3=读地址无应答
 *
 * 用法：固件烧好后保持 DAPLink 贴着，PC 上跑 tools/dap_dump.py 就会把
 * 这 288 字节读出来并翻译成表格。读到 magic 就算成功。
 *
 * 注意：这个模式会让两路舵机停在中位（不再抽动），这是正常的。
 * 定型后改 0，并配合 EAR_TELEM_MODE 一起关掉。 */
#ifndef EAR_DBG_SNAPSHOT
#define EAR_DBG_SNAPSHOT      0
#endif

/* 没找到传感器时的提示动作（和正常自检的"平滑长扫"一眼就能区分）。
 * 抽几下 = 卡在哪一步，每下之间停 140ms 方便数：
 *   2 下 = 认到了型号，但寄存器写不进去（克隆片没醒 / 配置被拒）
 *   3 下 = 地址上没有应答（接线 / 上拉 / 供电 / nCS 被拉低 / AD0）
 *   4 下 = 数据区探测/标定读失败，或运行中连续读失败；需读诊断记录区分
 *   5 下 = 扫到地址 ACK，但身份未知或身份读取失败；记录地址，等待匹配驱动
 *   6 下 = 能读能写但六轴数据恒为 0（芯片没真正唤醒，或根本不是这一族）
 *   7 下 = 系统节拍（SysTick）没跑起来，整个固件的时间逻辑都是死的
 *   8 下 = 事务拿到 ACK，但数据字节全是 0xFF（芯片应答了却不肯驱动数据线：
 *          没真正唤醒、或供电处在边界，比如 3.3V 灌进模块 VCC 被 LDO 压到 2.4V）
 *   9 下 = 读数据时"寄存器字节"拿不到 ACK —— 芯片认了地址但不认这个寄存器，
 *          说明这颗片子的寄存器映射不是 MPU 这一族（型号标错/假货）
 *  10 下 = 读数据时"读地址"拿不到 ACK —— 切换读写方向时从机掉线，时序临界
 * 运行中每 4s 再抽一次，避免"没检测到陀螺仪"看起来像死机。
 * 调试期建议保持 1，成品定型后可改 0。 */
#define EAR_FAULT_INDICATE    1
#define EAR_FAULT_PERIOD_MS   4000U

