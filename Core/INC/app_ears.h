/* 没找到传感器时的提示动作（和正常自检的"平滑长扫"一眼就能区分）。
 * 抽几下 = 卡在哪一步，每下之间停 140ms 方便数：
 *   2 下 = 认到了型号，但寄存器写不进去（克隆片没醒 / 配置被拒）
 *   3 下 = 地址上没有应答（接线 / 上拉 / 供电 / nCS 被拉低 / AD0）
 *   4 下 = 数据区探测/标定读失败，或运行中连续读失败；需读诊断记录区分
 *   5 下 = 扫到地址 ACK，但身份未知或身份读取失败；记录地址，等待匹配驱动
 *   6 下 = 能读能写但六轴数据恒为 0（芯片没真正唤醒，或根本不是这一族）
 *   7 下 = 系统节拍（SysTick）没跑起来，整个固件的时间逻辑都是死的
 *   8 下 = 事务拿到 ACK，但数据字节全是 0xFF（芯片应答了却不肯驱动数据线：
 *          没真正唤醒、或供电处在边界，比如 3.3V 灌进模块 VCC 被 LDO 压到 2.4V）
 *   9 下 = 读数据时"寄存器字节"拿不到 ACK —— 芯片认了地址但不认这个寄存器，
 *          说明这颗片子的寄存器映射不是 MPU 这一族（型号标错/假货）
 *  10 下 = 读数据时"读地址"拿不到 ACK —— 切换读写方向时从机掉线，时序临界
 * 运行中每 4s 再抽一次，避免"没检测到陀螺仪"看起来像死机。
 * 调试期建议保持 1，成品定型后可改 0。 */
