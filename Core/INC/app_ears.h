/*==============================================================================
 *  2. 陀螺仪总线
 *============================================================================*/
#define IMU_BUS_SOFT          0U   /* 软件模拟 I2C */
#define IMU_BUS_HW            1U   /* 硬件 I2C1 + HAL 库 */

/* 总线现在是**运行时自动选择**，不再需要在这里指定：
 * 上电后固件先用硬件 I2C1 跑一遍完整启动，不通再整体退回软件模拟 I2C，
 * 两条都失败才报故障码。
 *
 * 这样做的原因：这颗片子的表现是"配置寄存器（0x19/0x75）读得到正确值，
 * 数据寄存器（0x3B 起）却读不回来"，从电路上讲不通，必须实测分辨是
 * 软 I2C 的时序问题还是芯片本身的问题。硬件 I2C 的时序由外设产生，
 * 不受延时循环精度和中断抖动影响，正好可以当作参照。
 *
 * 如果以后想强行只用某一条，改 app_ears.c 里 IMU_BringUp() 调用
 * IMU_BringUpOnBus() 的那两行即可。 */

/* 软件 I2C 半比特延时循环次数：24MHz 下约 4us -> 总线约 80kHz。
 * 通信不稳就加大（更慢更稳），想更快就减小 */
#ifndef EAR_I2C_DELAY_LOOPS
#define EAR_I2C_DELAY_LOOPS   22U
#endif

/* 完整扫描普通 7 位从机地址，跳过 I2C 保留地址。
 * 0x68/0x69 仅作多个兼容器件同时存在时的优先级，不再限制搜索范围。 */
#define IMU_SCAN_ADDR_MIN     0x08U
#define IMU_SCAN_ADDR_MAX     0x77U
#define IMU_ADDR_PRIMARY      0x68U
#define IMU_ADDR_SECONDARY    0x69U

