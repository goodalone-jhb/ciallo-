#define IMU_CALIB_SAMPLES     150U

/*==============================================================================
 *  7. 对外数据结构
 *============================================================================*/
typedef struct
{
  float    pitch_deg;      /* 俯仰角，+ 抬头 / - 低头 */
  float    yaw_deg;        /* 累计转头角，+ 左转 / - 右转 */
  float    pitch_rate_dps; /* 俯仰角速度 */
  float    yaw_rate_dps;   /* 转头角速度 */
  uint16_t out1_us;        /* CH1 当前脉宽 */
  uint16_t out2_us;        /* CH2 当前脉宽 */
  uint8_t  imu_ok;         /* 1 = 陀螺仪在线 */
  uint8_t  imu_addr;       /* 实际使用的 7 位地址 */
  uint8_t  imu_whoami;     /* WHO_AM_I 读回值，0 = 没读到 */
  uint8_t  bus_err;        /* 总线错误计数（饱和到 255） */
} EarState_t;

/*==============================================================================
 *  8. 对外接口
 *============================================================================*/
void    Ear_Init(void);                    /* 上电初始化（须在 PWM 启动后调用） */
void    Ear_PowerUpDelay(void);            /* 上电静默：启动 PWM 前调用，见 EAR_POWERUP_DELAY_MS */
void    Ear_Task(void);                    /* 主循环里反复调用，内部 100Hz 节拍 */
uint8_t Ear_IsReady(void);                 /* 陀螺仪是否在线 */
void    Ear_GetState(EarState_t *st);      /* 取姿态/输出/诊断信息 */
void    Ear_SetPulseRaw(uint16_t us1, uint16_t us2); /* 手动打角，传 (0,0) 恢复闭环 */
void    Ear_SelfTest(void);                /* 手动触发一次行程自检（平滑长扫） */
void    Ear_FaultIndicate(void);           /* 手动触发一次"传感器异常"提示动作 */
void    Ear_Beacon(void);                  /* 手动触发一段开机慢摆信标 */
void    Ear_PinHeartbeat(uint8_t cycles);  /* 上电最早期心跳：PA0 输出 1Hz 方波，n 秒 */
void    Ear_SwPwmDemo(void);               /* 纯 GPIO 软件 PWM 扫描，不经过 TIM1 */
void    Ear_TelemetryReport(void) __attribute__((noreturn)); /* 故障时用频率报寄存器值（不返回） */
void    Ear_DbgSnapshotLoop(void) __attribute__((noreturn)); /* 故障时只写 RAM 快照，等 DAPLink 来读（不返回） */
void    Ear_PanicPark(void) __attribute__((noreturn)); /* HardFault 里调用：小幅快摆，表示"固件崩了"（不返回） */

